import time

for config in test_configs:
    problem_num = config[0]
    args = config[1]
    kwargs = config[2]
    generated_file = config[3] if len(config) > 3 else None
    
    try:
        # Get the current state of generated_files before running
        temp_gen_dir = PROJECT_ROOT / "generated_files"
        os.makedirs(temp_gen_dir, exist_ok=True)
        
        # Get pre-solution state
        pre_solution_state = {}
        if os.path.exists(temp_gen_dir):
            for file in os.listdir(temp_gen_dir):
                file_path = os.path.join(temp_gen_dir, file)
                if os.path.isfile(file_path):
                    pre_solution_state[file] = os.path.getmtime(file_path)
        
        # Run solution implementation
        solution_result = solution.run_problem(problem_num, *args, **kwargs)
        time.sleep(0.1)  # Small delay to ensure file timestamps differ
        
        # Copy new/modified files from solution
        if os.path.exists(temp_gen_dir):
            for file in os.listdir(temp_gen_dir):
                file_path = os.path.join(temp_gen_dir, file)
                if os.path.isfile(file_path):
                    # Check if file is new or modified
                    if file not in pre_solution_state or os.path.getmtime(file_path) > pre_solution_state[file]:
                        dst = SOLUTION_GEN_DIR / file
                        shutil.copy2(file_path, dst)
        
        # Get post-solution state for practice
        pre_practice_state = {}
        if os.path.exists(temp_gen_dir):
            for file in os.listdir(temp_gen_dir):
                file_path = os.path.join(temp_gen_dir, file)
                if os.path.isfile(file_path):
                    pre_practice_state[file] = os.path.getmtime(file_path)
        
        # Run practice implementation
        practice_result = practice.run_problem(problem_num, *args, **kwargs)
        time.sleep(0.1)  # Small delay
        
        # Copy new/modified files from practice
        if os.path.exists(temp_gen_dir):
            for file in os.listdir(temp_gen_dir):
                file_path = os.path.join(temp_gen_dir, file)
                if os.path.isfile(file_path):
                    # Check if file is new or modified during practice run
                    if file not in pre_practice_state or os.path.getmtime(file_path) > pre_practice_state[file]:
                        dst = PRACTICE_GEN_DIR / file
                        shutil.copy2(file_path, dst)
        
        # Compare results
        match, message = compare_results(problem_num, solution_result, practice_result)
        
        if match:
            results["passed"].append(problem_num)
            print(message)
        else:
            results["failed"].append(problem_num)
            failed_details.append((problem_num, args, message))
            print(message)
        
        # Compare generated files if specified
        if generated_file:
            file_match, file_message = compare_files(problem_num, generated_file)
            # Always print file comparison messages (including SKIPs)
            print(f"  {file_message}")
            # Track actual pass/fail results (not SKIPs)
            if file_match is not None:
                results["file_comparisons"].append((problem_num, file_match))
            
    except Exception as e:
        results["errors"].append((problem_num, str(e)))
