def compare_results(problem_num, solution_result, practice_result):
    """Compare returns from both implementations - check type and value"""
    solution_type = type(solution_result).__name__
    practice_type = type(practice_result).__name__
    
    # Check if types match
    if solution_type != practice_type:
        return False, f"[FAIL] Problem {problem_num}: Type mismatch\n  Solution type: {solution_type} = {solution_result}\n  Practice type: {practice_type} = {practice_result}"
    
    # Check if values match
    if solution_result != practice_result:
        return False, f"[FAIL] Problem {problem_num}: Value mismatch\n  Solution ({solution_type}): {solution_result}\n  Practice ({practice_type}): {practice_result}"
    
    return True, f"[PASS] Problem {problem_num}: Results match (type: {solution_type})"

def compare_files(problem_num, filename):
    """Dynamically compare generated files if they exist"""
    solution_file = SOLUTION_GEN_DIR / filename
    practice_file = PRACTICE_GEN_DIR / filename
    
    try:
        solution_exists = os.path.exists(solution_file)
        practice_exists = os.path.exists(practice_file)
        
        if not solution_exists and not practice_exists:
            return None, f"[SKIP] Problem {problem_num}: File '{filename}' not generated by either implementation"
        elif not solution_exists:
            return None, f"[SKIP] Problem {problem_num}: Solution file not found: {filename}"
        elif not practice_exists:
            return None, f"[SKIP] Problem {problem_num}: Practice file not found: {filename}"
        else:
            # Both files exist, compare them
            if filecmp.cmp(solution_file, practice_file, shallow=False):
                return True, f"[PASS] Problem {problem_num}: Generated files match"
            else:
                return False, f"[FAIL] Problem {problem_num}: Generated files differ"
    except Exception as e:
        return None, f"[ERROR] Problem {problem_num}: Could not compare files - {e}"

